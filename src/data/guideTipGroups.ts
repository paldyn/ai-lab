import type { TipAim, TipGroupId } from '../types/playbook';

export interface TipGroup {
  id: TipGroupId;
  /** 어느 축의 질문인가. 축마다 묻는 것이 다릅니다. */
  aim: TipAim;
  /**
   * 읽는 사람이 실제로 묻는 말. 묶음 머리글에 그대로 섭니다.
   *
   * **이름이 아니라 질문입니다.** 「상주 컨텍스트」처럼 이름을 붙이면 그것이 무엇을
   * 뜻하는지를 한 번 더 풀어야 하는데, 질문은 그 자체가 읽는 사람의 말이라 풀 것이
   * 없습니다. 넷을 세로로 읽으면 그대로 「이 제품을 쓰면서 물어볼 것들」이 됩니다.
   */
  question: string;
}

/**
 * 팁을 묶는 질문 — **축마다 넷씩이다.**
 *
 * **축을 등급에서 질문으로 옮긴 자리입니다**(2026-09-17). 그 전에는 팁 열여덟이
 * 같은 굵기·같은 모양으로 평평하게 한 줄로 섰고, 거르개가 가르는 것은 **공식이냐
 * 체감이냐**였습니다. 그런데 이 화면에 온 사람이 묻는 것은 그게 아니라 **「지금 뭘
 * 하면 되냐」**입니다.
 *
 * **두 축이 같은 넷을 쓰다가 갈랐습니다**(같은 날 저녁). 세션의 시간으로 짠 넷은
 * 아낌에는 잘 맞았지만(20·10·16·17) 잘 씀에서는 **서른둘 중 스물넷이 `feed` 하나**에
 * 몰렸습니다 — 제품 대부분이 「잘 쓰기」 절에 묶음을 하나만 세웠고, 묶음이 하나면
 * 묶은 뜻이 없습니다. **축이 다르면 묻는 것도 다릅니다.**
 *
 * **묶음에 「한 줄 답」을 안 답니다.** 처음 설계는 질문마다 답 문장을 하나씩 붙였는데,
 * 그 문장은 **배지도 출처도 반례도 없는 주장**이 됩니다 — 체감 팁을 압축해 적으면
 * 「체감 등급에는 넷이 다 있어야 한다」가 그 자리에서 깨지고, `npm test`(값)와
 * `check:playbook`(나이) 어느 쪽에도 안 걸린 채 늙습니다. 대신 **레버를 기계로
 * 뽑아 나열합니다**(`leversOf`) — 새로 쓰는 문장이 0이라 늙을 것이 없습니다.
 *
 * **묶음에 별명도 안 붙입니다.** 질문 위에 「짐 싸기」·「첫 줄에서」 같은 모노 라벨을
 * 한 줄 더 세웠다가 걷어냈습니다 — 넷이 시점·비유·되풀이로 제각각이라 위계가 아니라
 * 얼룩이었고, 질문이 이미 그 말을 하고 있었습니다.
 *
 * **축마다 넷을 넘기지 않습니다.** 다섯째를 만드는 순간 「기타」가 생겨 그 안이 다시
 * 위계 없는 목록이 됩니다. 넘칠 때 할 일은 칸을 늘리는 것이 아니라 **다시 가르는**
 * 것입니다 — 잘 씀 축의 `brief`가 「재료·경계·끝 조건을 담기」와 「흐릿하면 계획부터
 * 받기」 둘로 갈려 있어 넘치면 거기가 갈릴 자리입니다.
 */
export const guideTipGroups: TipGroup[] = [
  /* ── 아낌 — 세션이 지나는 시간 ───────────────────────────────── */
  { id: 'load', aim: 'save', question: '세션마다 따라붙는 것을 줄였나' },
  { id: 'model', aim: 'save', question: '어느 모델로, 어느 강도로 돌리나' },
  { id: 'feed', aim: 'save', question: '무엇을 넣고 무엇을 맡기나' },
  { id: 'cut', aim: 'save', question: '세션을 어디서 끊나' },

  /* ── 잘 씀 — 어긋남을 어디서 잡나 (고치는 값이 커지는 순서) ────
     팁 본문 셋이 이 차례를 직접 말한다 — 「어긋난 채로 결과물을 다 만들고 나서
     고치는 것이 가장 비싸다」·「엉뚱한 범위로 한 번 다 돌린 뒤 다시 시키는 것이
     가장 비싼 실수」·「계획이 다 나온 뒤 되돌리는 것보다 낫다」.

     **2번과 3번을 가르는 선은 「어디에 적나」가 아니라 실행이 한 번이라도 일어났는가**
     다. 계획 모드·인터뷰·조사 계획은 본 작업 전에 방향을 맞추는 것이라 2번이고,
     도중 끼어들기·구간 고치기·되감기는 이미 나온 것을 상대하므로 3번이다.

     **2번과 4번이 둘 다 「프롬프트 한 줄」이라 헷갈릴 수 있다.** 확인 수단·자기
     점검·출처 대기는 전부 요청에 적는 문장인데 4번에 있다 — 축이 「어디에 적나」가
     아니라 「어긋남을 어디서 잡나」라서 목적을 따른다. */
  { id: 'standing', aim: 'well', question: '매번 다시 말하는 것을 박아 뒀나' },
  { id: 'brief', aim: 'well', question: '시작하기 전에 서로 맞춰 봤나' },
  { id: 'steer', aim: 'well', question: '어긋난 것을 다시 시키지 않고 그 자리만 고치나' },
  { id: 'verdict', aim: 'well', question: '됐다는 판정을 누가 하나' },
];

/** 그 축의 질문 넷. 배열 순서가 곧 화면 순서입니다. */
export const tipGroupsOf = (aim: TipAim): TipGroup[] =>
  guideTipGroups.filter((g) => g.aim === aim);

export const tipGroupIdsOf = (aim: TipAim): TipGroupId[] =>
  tipGroupsOf(aim).map((g) => g.id);

export const tipGroupIds = guideTipGroups.map((g) => g.id);

const byId = new Map(guideTipGroups.map((g) => [g.id, g]));
export const tipGroupById = (id: string): TipGroup | undefined => byId.get(id as never);

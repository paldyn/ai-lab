/**
 * 목차 번호.
 *
 * **번호는 자리를 세는 것이지 항목을 세는 것이 아닙니다.** 예전에는 목차가
 * `index + 1`을 그대로 찍어서, 하위 항목이 낀 글에서는 절 번호가 그만큼 건너뛰었습니다
 * — `##`이 셋인데 사이에 `###`이 둘 끼면 마지막 절이 05번이 됩니다. 하위 항목에는
 * 번호가 아예 없어서 「몇 번째 절의 몇 번째 갈래인가」도 알 수 없었습니다.
 *
 * 위 단계는 `01.`처럼 점을 달고, 아래 단계는 그 절의 번호를 물려받아 `03.2`가 됩니다.
 * 점이 있어야 번호와 제목이 눈으로 갈립니다.
 */
export function tocNumbers(subs: readonly boolean[]): string[] {
  let top = 0;
  let sub = 0;

  return subs.map((isSub) => {
    /*
      하위가 위 단계보다 먼저 오면(문서가 `###`으로 시작하는 경우) 그것을 위 단계로
      셉니다. 「00.1」은 어느 절에도 안 붙는 번호라 없느니만 못합니다.
    */
    if (!isSub || top === 0) {
      top += 1;
      sub = 0;
      return `${String(top).padStart(2, '0')}.`;
    }

    sub += 1;
    return `${String(top).padStart(2, '0')}.${sub}`;
  });
}
